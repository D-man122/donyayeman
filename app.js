  async function autoFillMusic() {
    if (autoRunning || hasMusicData()) return;
    if (!isAdmin() && !(Api.items && typeof Api.items.seedMany === 'function')) return;
    // موج اول: ۱۲ خواننده‌ی جهان و ۵ خواننده‌ی ایران همزمان (۱۷ درخواست در یک لحظه) تا صفحه‌ی موزیک تقریباً فوراً پر بشه
    const burst = MU_W.slice(0, 12).map((x) => ['world', x]).concat(MU_I.slice(0, 5).map((x) => ['iran', x]));
    const rest = MU_W.slice(12).map((x) => ['world', x]).concat(MU_I.slice(5).map((x) => ['iran', x]));
    const total = burst.length + rest.length;
    let p = 0;
    try { p = Number(localStorage.getItem('dm:autofill-music-p') || 0); } catch (e) { return; }
    if (p >= total) return;
    if (p === 0 && state.items.some((i) => i.cat === 'music')) { try { localStorage.setItem('dm:autofill-music-p', String(total)); } catch (e) { /* مهم نیست */ } return; }
    const save = (n) => { try { localStorage.setItem('dm:autofill-music-p', String(n)); } catch (e) { /* مهم نیست */ } };
    autoRunning = true;
    try {
      if (p < burst.length) {
        await Promise.all(burst.map((x) => bulkImport([x[1]], x[0], 8)));
        save(burst.length); p = burst.length;
        await refresh();
      }
      // بقیه‌ی خواننده‌ها یواش‌یواش و بعد از یه مکث (iTunes حدود ۲۰ درخواست در دقیقه قبول می‌کنه)
      if (p < total) await new Promise((r) => setTimeout(r, 62000));
      for (; p < total; p++) {
        const x = rest[p - burst.length];
        const got = await bulkImport([x[1]], x[0], 8);
        save(p + 1);
        if (got > 0) await refresh();
        await new Promise((r) => setTimeout(r, 3200));
      }
    } catch (e) { /* مهم نیست */ }
    autoRunning = false;
    return true;
  }

